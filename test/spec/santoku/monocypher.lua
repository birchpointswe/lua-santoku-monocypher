test("sign_request and verify_request", function ()
  local id = crypto.derive_identity("test-secret")
  local body = "request body"
  local sig = id:sign_request(body)
  assert(type(sig) == "string")
  local ok, err = crypto.verify_request(id:public_key(), sig, id:sub(), body)
  assert(ok == true, err)
end)

test("verify_request wrong signature fails", function ()
  local id = crypto.derive_identity("test-secret")
  local body = "request body"
  local id2 = crypto.derive_identity("other-secret")
  local sig2 = id2:sign_request(body)
  local ok, errmsg = crypto.verify_request(id:public_key(), sig2, id:sub(), body)
  assert(ok == nil)
  assert(errmsg == "invalid_signature")
end)

test("generate passphrase", function ()
  local secret = crypto.generate()
  assert(type(secret) == "string")
  local words = {}
  for w in secret:gmatch("%S+") do
    words[#words + 1] = w
  end
  assert(#words == 6)
end)

test("validate passphrase", function ()
  local secret = crypto.generate()
  assert(crypto.validate(secret) == true)
end)

test("validate rejects 20-char path", function ()
  assert(crypto.validate("Sh0rt!Pass") == false)
  assert(crypto.validate("ThisIsALongPassword1!") == false)
end)

test("validate rejects short diceware", function ()
  assert(crypto.validate("abacus abdomen abdominal abide abiding ability") == true)
  assert(crypto.validate("abacus abdomen abdominal abide abiding") == false)
end)

test("validate invalid passphrase", function ()
  assert(crypto.validate("invalid-words-here-now-test-foo") == false)
end)

test("validate accepts hyphenated EFF entries", function ()
  assert(crypto.validate("abacus abdomen abdominal abide abiding ability felt-tip drop-down") == true)
  assert(crypto.validate("t-shirt yo-yo abacus abdomen abdominal abide abiding ability") == true)
end)

test("validate accepts every output of generate (1000 iter)", function ()
  for _ = 1, 1000 do
    local secret = crypto.generate()
    assert(crypto.validate(secret) == true, "generate produced invalid: " .. secret)
  end
end)

