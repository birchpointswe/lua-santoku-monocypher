test("wrap_key unwrap_key roundtrip", function ()
  local id = crypto.derive_identity("test-secret")
  local key = crypto.derive_key("test-secret", id)
  local wrap = string.rep(string.char(0x42), 32)
  local wrapped = crypto.wrap_key(key, wrap)
  assert(type(wrapped) == "string")
  local unwrapped = crypto.unwrap_key(wrapped, wrap)
  assert(unwrapped ~= nil)
  assert(unwrapped:export() == key:export())
end)

test("unwrap_key with wrong wrap fails", function ()
  local id = crypto.derive_identity("test-secret")
  local key = crypto.derive_key("test-secret", id)
  local wrap1 = string.rep(string.char(0x42), 32)
  local wrap2 = string.rep(string.char(0x43), 32)
  local wrapped = crypto.wrap_key(key, wrap1)
  local result, errmsg = crypto.unwrap_key(wrapped, wrap2)
  assert(result == nil)
  assert(errmsg == "decryption failed")
end)

test("wrap_key rejects wrong wrap size", function ()
  local id = crypto.derive_identity("test-secret")
  local key = crypto.derive_key("test-secret", id)
  local result, errmsg = crypto.wrap_key(key, "tooshort")
  assert(result == nil)
  assert(errmsg == "wrap_bytes must be exactly 32 bytes")
end)

test("hmac_sha256 deterministic hex", function ()
  local h1 = crypto.hmac_sha256("k", "message")
  local h2 = crypto.hmac_sha256("k", "message")
  assert(type(h1) == "string")
  assert(#h1 == 64)
  assert(h1 == h2)
  assert(crypto.hmac_sha256("k2", "message") ~= h1)
end)

test("hmac_sha1 rfc 2202 vectors", function ()
  local function bytes (...)
    return string.char(...)
  end
  assert(crypto.hmac_sha1(string.rep(bytes(0x0b), 20), "Hi There")
    == "b617318655057264e28bc0b6fb378c8ef146be00")
  assert(crypto.hmac_sha1("Jefe", "what do ya want for nothing?")
    == "effcdf6ae5eb2fa2d27416d5f184df9c259a7c79")
  assert(crypto.hmac_sha1(string.rep(bytes(0xaa), 20), string.rep(bytes(0xdd), 50))
    == "125d7342b9ac11cd91a39af48aa17b4f63f175d3")
  local key4 = {}
  for i = 1, 25 do key4[i] = i end
  assert(crypto.hmac_sha1(bytes(arr.spread(key4)), string.rep(bytes(0xcd), 50))
    == "4c9007f4026250c6bc8414f9bf50c86c2d7235da")
  assert(crypto.hmac_sha1(string.rep(bytes(0x0c), 20), "Test With Truncation")
    == "4c1a03424b55e07fe7f27be1d58bb9324a9a5a04")
  assert(crypto.hmac_sha1(string.rep(bytes(0xaa), 80),
    "Test Using Larger Than Block-Size Key - Hash Key First")
    == "aa4ae5e15272d00e95705637ce8a3b55ed402112")
  assert(crypto.hmac_sha1(string.rep(bytes(0xaa), 80),
    "Test Using Larger Than Block-Size Key and Larger Than One Block-Size Data")
    == "e8e99d0f45237d786d6bbaa7965c7808bbff1a91")
end)

test("key hmac deterministic hex", function ()
  local id = crypto.derive_identity("test-secret")
  local key = crypto.derive_key("test-secret", id)
  local h = key:hmac("message")
  assert(type(h) == "string")
  assert(#h == 64)
  assert(key:hmac("message") == h)
end)

test("key bytes returns raw 32-byte material", function ()
  local id = crypto.derive_identity("test-secret")
  local key = crypto.derive_key("test-secret", id)
  local raw = key:bytes()
  assert(type(raw) == "string")
  assert(#raw == 32)

  assert(key:bytes() == raw)
  assert(raw ~= key:export())

  assert(crypto.import_key(key:export()):bytes() == raw)
end)

test("key derive produces domain-separated subkeys", function ()
  local id = crypto.derive_identity("test-secret")
  local key = crypto.derive_key("test-secret", id)
  local a = key:derive("db")
  local b = key:derive("db")
  local c = key:derive("search")
  assert(#a:bytes() == 32)

  assert(a:bytes() == b:bytes())

  assert(a:bytes() ~= c:bytes())

  assert(a:bytes() ~= key:bytes())

  local ct = a:encrypt("hello")
  assert(a:decrypt(ct) == "hello")
  assert(c:decrypt(ct) == nil)
end)
